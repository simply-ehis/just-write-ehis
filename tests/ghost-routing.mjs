/**
 * ghost-routing — behavioral checks for ghost's provider routing
 * (src/lib/ghost.ts).
 *
 * Regression under test: the small slot's DEFAULT address is the bundled
 * LLM's own private socket. Ghost's "fall through to the small slot when the
 * local LLM fails" therefore reconnected to the exact server that had just
 * refused it, surfacing `llm socket connect failed ... (os error 10061)`.
 *
 * `$lib/api` is replaced by an esbuild onResolve stub so each case can see
 * which backend ghost actually reached, and `isBrowserPreview()` reports
 * false so the desktop guard (the one under test) is the path taken. A test
 * entry re-exports ghost + settings + the stub from ONE bundle, so the
 * settings store mutated here is the same instance ghost reads.
 *
 * Run: node tests/ghost-routing.mjs (no build needed)
 */
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { get } from "svelte/store";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const memory = new Map();
globalThis.localStorage = {
  getItem: (key) => memory.get(key) ?? null,
  setItem: (key, value) => memory.set(key, String(value)),
  removeItem: (key) => memory.delete(key),
};

const outdir = join(root, "tests", ".tmp-ghost-routing");
await mkdir(outdir, { recursive: true });

const stubPath = join(outdir, "api-stub.mjs");
await writeFile(
  stubPath,
  `// Generated by tests/ghost-routing.mjs — records which backend ghost reaches.
export const calls = [];
export function resetCalls() { calls.length = 0; }
export function isBrowserPreview() { return false; }
export const api = {
  aiGenerate: async (request) => { calls.push(["aiGenerate", request]); return { content: "small-slot reply" }; },
  llmCompletion: async () => { calls.push(["llmCompletion"]); return "ghost reply"; },
  llmIsRunning: async () => false,
  // Simulate a sidecar that will not come up: ensureLlm() fails fast here.
  llmStart: async () => { throw new Error("llama-server missing"); },
  llmHealth: async () => ({ status: "unavailable" }),
  llmStop: async () => {},
  // Settings hydrates these at import time; null keeps hydration quiet.
  secretGet: async () => null,
  secretSet: async () => {},
};
`,
);

const entryPath = join(outdir, "entry.ts");
await writeFile(
  entryPath,
  `export { requestGhostContinuation, ghostStatus } from "$lib/ghost";
export { settings } from "$lib/stores/settings";
export { calls, resetCalls } from "$lib/api";
`,
);

const esbuild = await import("esbuild");
const outfile = join(outdir, "entry.mjs");
await esbuild.build({
  entryPoints: [entryPath],
  bundle: true,
  platform: "node",
  format: "esm",
  alias: { $lib: join(root, "src/lib") },
  plugins: [
    {
      name: "stub-api",
      setup(build) {
        build.onResolve({ filter: /^\$lib\/api$/ }, () => ({ path: stubPath }));
      },
    },
  ],
  outfile,
  logLevel: "silent",
});
const bundle = await import(pathToFileURL(outfile).href);

const SENTINEL = "http://127.0.0.1:8093/v1";
const REMOTE = "https://api.openai.com/v1";
const SENTENCE = "She closed the door and";

let failures = 0;
function check(name, ok, detail = "") {
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? ` — ${detail}` : ""}`);
  if (!ok) failures++;
}
const reached = (name) => bundle.calls.some(([called]) => called === name);
const configure = (patch) => bundle.settings.update((s) => ({ ...s, ...patch }));
const status = () => get(bundle.ghostStatus);

// Bundled LLM off, small slot left on its default (sentinel) address.
{
  configure({ llmEnabled: false, smallModelEndpoint: SENTINEL });
  bundle.resetCalls();
  const out = await bundle.requestGhostContinuation(SENTENCE);
  check("sentinel fallback returns no suggestion", out === null);
  check("sentinel fallback never calls ai_generate", !reached("aiGenerate"), bundle.calls.map(([n]) => n).join(",") || "no backend reached");
  check("sentinel fallback reports unavailable", status().state === "unavailable", status().detail);
}

// Local first path fails (llmStart throws) — must not reconnect to itself.
{
  configure({ llmEnabled: true, smallModelEndpoint: SENTINEL });
  bundle.resetCalls();
  const out = await bundle.requestGhostContinuation(SENTENCE);
  check("failed local start does not fall back onto itself", out === null);
  check("failed local start reaches no backend", !reached("aiGenerate") && !reached("llmCompletion"), bundle.calls.map(([n]) => n).join(",") || "no backend reached");
}

// Guard must not over-block: a genuinely remote small slot still serves.
{
  configure({ llmEnabled: false, smallModelEndpoint: REMOTE });
  bundle.resetCalls();
  const out = await bundle.requestGhostContinuation(SENTENCE);
  check("remote small slot still serves the fallback", out === "small-slot reply");
  check("remote small slot is reached via ai_generate", reached("aiGenerate"));
  check("remote fallback reports ok", status().state === "ok");
}

await rm(outdir, { recursive: true, force: true });

console.log(failures === 0 ? "GHOST-ROUTING ALL PASS" : `GHOST-ROUTING ${failures} FAILURE(S)`);
process.exit(failures === 0 ? 0 : 1);
